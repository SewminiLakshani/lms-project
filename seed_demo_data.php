// ---------------- Helper: generate a real, valid mini PDF file ----------------
// This avoids "Not Found" errors on demo download links by actually writing
// a small (but valid) PDF to disk instead of just inserting a fake filename.
function generateSimplePdf($titleText) {
    $objects = [];
    $objects[1] = "1 0 obj\n<< /Type /Catalog /Pages 2 0 R >>\nendobj\n";
    $objects[2] = "2 0 obj\n<< /Type /Pages /Kids [3 0 R] /Count 1 >>\nendobj\n";
    $objects[3] = "3 0 obj\n<< /Type /Page /Parent 2 0 R /MediaBox [0 0 612 792] /Contents 4 0 R /Resources << /Font << /F1 5 0 R >> >> >>\nendobj\n";
    $safeText = str_replace(['(', ')'], ['\\(', '\\)'], $titleText);
    $streamText = "BT /F1 16 Tf 50 700 Td ($safeText) Tj ET\nBT /F1 11 Tf 50 670 Td (This is a demo placeholder file generated by seed_demo_data.php) Tj ET";
    $streamLen = strlen($streamText);
    $objects[4] = "4 0 obj\n<< /Length $streamLen >>\nstream\n$streamText\nendstream\nendobj\n";
    $objects[5] = "5 0 obj\n<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica >>\nendobj\n";

    $pdf = "%PDF-1.4\n";
    $offsets = [];
    foreach ($objects as $num => $obj) {
        $offsets[$num] = strlen($pdf);
        $pdf .= $obj;
    }
    $xrefStart = strlen($pdf);
    $count = count($objects) + 1;
    $pdf .= "xref\n0 $count\n0000000000 65535 f \n";
    for ($i = 1; $i <= count($objects); $i++) {
        $pdf .= sprintf("%010d 00000 n \n", $offsets[$i]);
    }
    $pdf .= "trailer\n<< /Size $count /Root 1 0 R >>\nstartxref\n$xrefStart\n%%EOF";
    return $pdf;
}

function writePlaceholderFile($subfolder, $filename, $content) {
    $dir = __DIR__ . "/assets/uploads/$subfolder/";
    if (!is_dir($dir)) { mkdir($dir, 0777, true); }
    file_put_contents($dir . $filename, $content);
}

